const { test, expect } = require('@playwright/test');
const authenticate = require('./auth-fixture.cjs');

test('nested list drag updates node order without losing nodes', async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => { errors.push(error.message); console.error(error); });
  await authenticate(page);
  await page.goto('./#/app/ui/list-groups');
  const tree = page.locator('.rst__tree').first();
  const titles = tree.locator('.rst__rowTitle');
  await expect(titles.first()).toBeVisible({ timeout: 30000 });
  const before = await titles.allTextContents();
  const source = tree.locator('.rst__row').filter({ has: page.getByText('Item 1', { exact: true }) }).locator('.rst__moveHandle');
  const target = tree.locator('.rst__row').filter({ has: page.getByText('Item 3', { exact: true }) });
  await expect(source).toHaveAttribute('draggable', 'true');
  await source.scrollIntoViewIfNeeded();
  await target.scrollIntoViewIfNeeded();
  const start = await source.boundingBox();
  const end = await target.boundingBox();
  await page.mouse.move(start.x + start.width / 2, start.y + start.height / 2);
  await page.mouse.down();
  await page.mouse.move(start.x + start.width / 2 + 10, start.y + start.height / 2 + 10, { steps: 3 });
  await page.mouse.move(start.x + start.width / 2 + 44, end.y + end.height / 2, { steps: 20 });
  await page.mouse.move(start.x + start.width / 2 + 45, end.y + end.height / 2, { steps: 2 });
  await page.mouse.up();
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await expect.poll(() => titles.allTextContents(), { timeout: 5000 }).not.toEqual(before);
  const after = await titles.allTextContents();
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  expect(await titles.allTextContents()).toEqual(after);
  await expect(titles).toHaveCount(before.length);
  await expect(page.getByText('Item 1', { exact: true }).first()).toBeVisible();
  const cancelSource = tree.locator('.rst__moveHandle').first();
  const cancelTarget = tree.locator('.rst__row').nth(2);
  await cancelSource.scrollIntoViewIfNeeded();
  await cancelTarget.scrollIntoViewIfNeeded();
  const cancelStart = await cancelSource.boundingBox();
  const cancelEnd = await cancelTarget.boundingBox();
  await page.mouse.move(cancelStart.x + 20, cancelStart.y + 20);
  await page.mouse.down();
  await page.mouse.move(cancelStart.x + 30, cancelStart.y + 30, { steps: 3 });
  await page.mouse.move(cancelStart.x + 64, cancelEnd.y + 20, { steps: 20 });
  await page.keyboard.press('Escape');
  await page.mouse.up();
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  expect(await titles.allTextContents()).toEqual(after);
  await page.screenshot({ path: 'test-results/one-tree-drag.png' });
  expect(errors).toEqual([]);
});

test('independent trees reject cross-tree drops without losing nodes', async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => { errors.push(error.message); console.error(error); });
  await authenticate(page);
  await page.goto('./#/app/ui/list-groups');
  const trees = page.locator('.rst__tree');
  await expect(trees.first().locator('.rst__rowTitle').first()).toBeVisible({ timeout: 30000 });
  const first = trees.nth(0).locator('.rst__rowTitle');
  const second = trees.nth(1).locator('.rst__rowTitle');
  const beforeFirst = await first.allTextContents(), beforeSecond = await second.allTextContents();
  const source = trees.nth(0).locator('.rst__row').filter({ has: page.getByText('Item 1', { exact: true }) }).locator('.rst__moveHandle');
  const target = trees.nth(1).locator('.rst__row').filter({ has: page.getByText('Item 14', { exact: true }) });
  await source.scrollIntoViewIfNeeded(); await target.scrollIntoViewIfNeeded();
  const start = await source.boundingBox(), end = await target.boundingBox();
  await page.mouse.move(start.x + 20, start.y + 20); await page.mouse.down();
  await page.mouse.move(start.x + 30, start.y + 30, { steps: 3 });
  await page.mouse.move(end.x + 20, end.y + 20, { steps: 20 });
  await page.mouse.up();
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await expect(first).toHaveCount(beforeFirst.length);
  await expect(second).toHaveCount(beforeSecond.length);
  expect(await first.allTextContents()).toEqual(beforeFirst);
  expect(await second.allTextContents()).toEqual(beforeSecond);
  const afterFirst = await first.allTextContents(), afterSecond = await second.allTextContents();
  expect([...afterFirst, ...afterSecond].sort()).toEqual([...beforeFirst, ...beforeSecond].sort());
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  expect(await first.allTextContents()).toEqual(afterFirst); expect(await second.allTextContents()).toEqual(afterSecond);
  expect(errors).toEqual([]);
});
